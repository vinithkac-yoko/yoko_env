"""Write docs/TOOLS.md: every tool in plain words, for the pattern makers to check the names.

uv run python scripts/tool_catalog.py          # write the file
uv run python scripts/tool_catalog.py --check  # fail if the file is out of date
"""

import sys
from pathlib import Path

from yoko_tools.spec import all_tools

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs/TOOLS.md"
GROUPS = [
    ("Points", lambda s: s.tier == "primitive" and s.name.startswith(("point_", "cut_", "true_"))),
    (
        "Lines, arcs and curves",
        lambda s: s.tier == "primitive" and s.name.startswith(("line", "arc_", "curve_")),
    ),
    (
        "Copying: mirror, rotate, move",
        lambda s: (
            s.tier == "primitive"
            and s.name in ("mirror_by_line", "mirror_by_axis", "rotate", "move")
        ),
    ),
    ("Variables", lambda s: s.tier == "variable"),
    ("Pieces and blocks", lambda s: s.tier == "structure"),
    ("Looking (these never change the pattern)", lambda s: s.tier == "read"),
    ("Library", lambda s: s.tier == "library"),
]


def first_sentence(text: str) -> str:
    return text.split("\n")[0].strip()


def build() -> str:
    specs = all_tools(ROOT / "config/tools")
    written = {k: v for k, v in specs.items() if v.derived_from is None}
    lines = [
        "# Tools",
        "",
        "Every tool the drafting agent can use, in plain words. Written from `config/tools/*.yaml`"
        " (`uv run python scripts/tool_catalog.py`); do not edit this file by hand.",
        "",
        "**Please check the names.** They are the words the agent sees. If a name is not the word you"
        " would use, say which one and what you would call it.",
        "",
        "Every tool that makes a point, line, arc or curve also has an `edit_<tool>` (change its"
        " numbers or what it refers to) and a `delete_<tool>` (remove it, refused if anything uses it)."
        " They are made from the creating tool, so they are not listed again.",
        "",
    ]
    for title, test in GROUPS:
        group = [s for s in written.values() if test(s)]
        if not group:
            continue
        lines += [
            f"## {title}",
            "",
            "| Tool | What it does | When to use it |",
            "| --- | --- | --- |",
        ]
        for s in sorted(group, key=lambda s: s.name):
            use = (
                s.description.split("Use it when ", 1)[1].split(". Do not")[0]
                if "Use it when " in s.description
                else ""
            )
            lines.append(f"| `{s.name}` | {first_sentence(s.description)} | {use} |")
        lines.append("")
    count = len(specs)
    lines.append(
        f"{len(written)} tools are written; with the derived edit and delete tools there are {count}."
    )
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            sys.exit("docs/TOOLS.md is out of date: run scripts/tool_catalog.py")
    else:
        OUT.write_text(text)
        print(f"wrote {OUT.relative_to(ROOT)}")
